var iamTestTime = time.Date(2026, 10, 28, 1, 2, 3, 0, time.UTC)

func iamTestVerifier() *iamVerifier {
	verifier := newIAMVerifier("us-east-1", map[string]iamCredential{
		"local-example-key": {
			secretAccessKey: "local-example-secret",
			identity:        iamIdentity{AccountID: "111122223333", UserARN: "arn:aws:iam::111122223333:user/worker", UserID: "AID-local", CallerID: "AID-local"},
		},
	})
	verifier.now = func() time.Time { return iamTestTime }
	return verifier
}

// This is an independent official SDK signing control, not a copy of the
// verifier's canonical-request or HMAC implementation.
func iamSDKRequest(t *testing.T, method, path string, body []byte, timestamp time.Time, token string) *http.Request {
	t.Helper()
	clientRequest, err := http.NewRequestWithContext(context.Background(), method, "http://local.example.test:4180"+path, bytes.NewReader(body))
	require.NoError(t, err)
	clientRequest.Header.Set("Content-Type", "application/octet-stream")
	clientRequest.Header.Set("X-Request-Id", "caller-request-id")
	clientRequest.Header.Set("X-Correlation-Id", "caller-correlation-id")
	clientRequest.Header["X-Repeated"] = []string{"first  value", "second value"}
	digest := sha256.Sum256(body)
	require.NoError(t, v4.NewSigner().SignHTTP(t.Context(), aws.Credentials{
		AccessKeyID: "local-example-key", SecretAccessKey: "local-example-secret", SessionToken: token,
	}, clientRequest, hex.EncodeToString(digest[:]), "execute-api", "us-east-1", timestamp))
	incoming := httptest.NewRequest(method, clientRequest.URL.String(), bytes.NewReader(body))
	incoming.Header = clientRequest.Header.Clone()
	incoming.Host = clientRequest.Host
	incoming.ContentLength = clientRequest.ContentLength
	return incoming
}

func TestIAMVerifierSDKRequestsPreserveOriginalRequest(t *testing.T) {
	for _, path := range []string{
		"/edge/v1/items/example%2Fhistory?tag=b&tag=a&literal=%252F&space=%20&a-=value&a=first",
		"/edge/v1/items/example%252Fhistory",
		"/edge/v1/items/space%20and%2Bplus/%E9%9B%AA",
		"/edge/v1/items/back%5Cslash",
	} {
		for _, body := range [][]byte{nil, []byte{0, 'n', 'a', 't', 'i', 'v', 'e', 255}} {
			t.Run(path+"/"+iamBodyName(body), func(t *testing.T) {
				verifier := iamTestVerifier()
				method := http.MethodGet
				if len(body) != 0 {
					method = http.MethodPost
				}
				request := iamSDKRequest(t, method, path, body, iamTestTime, "")
				headers, target, host := request.Header.Clone(), *request.URL, request.Host
				identity, captured, status := verifier.authenticate(request)
				require.Zero(t, status)
				require.True(t, bytes.Equal(body, captured))
				require.Equal(t, "local-example-key", identity.AccessKey)
				require.Equal(t, "111122223333", identity.AccountID)
				require.Equal(t, "arn:aws:iam::111122223333:user/worker", identity.UserARN)
				require.Equal(t, "AID-local", identity.UserID)
				require.Equal(t, headers, request.Header)
				require.Equal(t, target, *request.URL)
				require.Equal(t, host, request.Host)
			})
		}
	}
}

func iamBodyName(body []byte) string {
	if len(body) == 0 {
		return "empty"
	}
	return "binary"
}

func TestIAMVerifierFrozenBotocoreControlWithoutSignedContentLength(t *testing.T) {
	// Generated by unchanged pinned botocore 1.40.76 SigV4Auth with the local
	// example credentials and timestamp below. Includes independently signed
	// escaped components, unsorted/repeated query values and repeated headers
	// containing both spaces and tabs. No Python dependency is needed to replay.
	body := []byte{0, 'n', 'a', 't', 'i', 'v', 'e', 255}
	request := httptest.NewRequest(http.MethodPost,
		"http://127.0.0.1:14180/edge/v1/items/example%2Fhistory?tag=b&tag=a&literal=%252F&space=%20&a-=value&a=first",
		bytes.NewReader(body))
	request.Header = http.Header{
		"Content-Type":         {"application/octet-stream"},
		"X-Repeated":           {"first  value", "second\tvalue"},
		"X-Amz-Date":           {"20261028T010203Z"},
		"X-Amz-Security-Token": {"local-example-token"},
		"Authorization":        {"AWS4-HMAC-SHA256 Credential=local-example-key/20261028/us-east-1/execute-api/aws4_request, SignedHeaders=content-type;host;x-amz-date;x-amz-security-token;x-repeated, Signature=e9236cd33602b705d021e4206ff6ccf98ab1f7785b52ab2b33a856c9da39cd9a"},
	}
	verifier := iamTestVerifier()
	credential := verifier.credentials["local-example-key"]
	credential.sessionToken = "local-example-token"
	verifier.credentials["local-example-key"] = credential
	originalQuery := request.URL.RawQuery
	identity, captured, status := verifier.authenticate(request)
	require.Zero(t, status)
	require.Equal(t, "local-example-key", identity.AccessKey)
	require.True(t, bytes.Equal(body, captured))
	require.Equal(t, originalQuery, request.URL.RawQuery, "verification must not normalize native rawQueryString")
}

type iamReadTracker struct {
	reader io.Reader
	reads  int
	closed bool
}

func (tracker *iamReadTracker) Read(destination []byte) (int, error) {
	tracker.reads++
	return tracker.reader.Read(destination)
}
func (tracker *iamReadTracker) Close() error { tracker.closed = true; return nil }

func TestIAMVerifierRejectsAuthenticationMetadataBeforeBodyRead(t *testing.T) {
	tests := []struct {
		name   string
		change func(*http.Request)
	}{
		{"missing authorization", func(r *http.Request) { r.Header.Del("Authorization") }},
		{"duplicate authorization", func(r *http.Request) { r.Header.Add("Authorization", r.Header.Get("Authorization")) }},
		{"case ambiguous authorization", func(r *http.Request) { r.Header["authorization"] = []string{r.Header.Get("Authorization")} }},
		{"unknown key", func(r *http.Request) {
			r.Header.Set("Authorization", strings.Replace(r.Header.Get("Authorization"), "local-example-key/", "unknown/", 1))
		}},
		{"wrong region", func(r *http.Request) {
			r.Header.Set("Authorization", strings.Replace(r.Header.Get("Authorization"), "/us-east-1/", "/eu-west-1/", 1))
		}},
		{"wrong service", func(r *http.Request) {
			r.Header.Set("Authorization", strings.Replace(r.Header.Get("Authorization"), "/execute-api/", "/s3/", 1))
		}},
		{"wrong date scope", func(r *http.Request) {
			r.Header.Set("Authorization", strings.Replace(r.Header.Get("Authorization"), "/20261028/", "/20261027/", 1))
		}},
		{"wrong terminator", func(r *http.Request) {
			r.Header.Set("Authorization", strings.Replace(r.Header.Get("Authorization"), "aws4_request", "other_request", 1))
		}},
		{"wrong algorithm", func(r *http.Request) {
			r.Header.Set("Authorization", strings.Replace(r.Header.Get("Authorization"), "AWS4-HMAC-SHA256", "AWS4-ECDSA-P256-SHA256", 1))
		}},
		{"duplicate field", func(r *http.Request) {
			r.Header.Set("Authorization", r.Header.Get("Authorization")+", Credential=another")
		}},
		{"bad signature encoding", func(r *http.Request) {
			r.Header.Set("Authorization", r.Header.Get("Authorization")[:len(r.Header.Get("Authorization"))-1]+"z")
		}},
		{"missing date", func(r *http.Request) { r.Header.Del("X-Amz-Date") }},
		{"duplicate date", func(r *http.Request) { r.Header.Add("X-Amz-Date", r.Header.Get("X-Amz-Date")) }},
		{"malformed date", func(r *http.Request) { r.Header.Set("X-Amz-Date", "2026-10-28T01:02:03Z") }},
		{"expired date", func(r *http.Request) {
			r.Header.Set("X-Amz-Date", iamTestTime.Add(-5*time.Minute-time.Second).Format(iamTimeFormat))
		}},
		{"future date", func(r *http.Request) {
			r.Header.Set("X-Amz-Date", iamTestTime.Add(5*time.Minute+time.Second).Format(iamTimeFormat))
		}},
		{"missing signed header", func(r *http.Request) { r.Header.Del("X-Repeated") }},
		{"unsorted signed headers", func(r *http.Request) {
			r.Header.Set("Authorization", strings.Replace(r.Header.Get("Authorization"), "content-length;content-type;", "content-type;content-length;", 1))
		}},
		{"duplicate signed header", func(r *http.Request) {
			r.Header.Set("Authorization", strings.Replace(r.Header.Get("Authorization"), ";host;", ";host;host;", 1))
		}},
		{"missing signed host", func(r *http.Request) {
			r.Header.Set("Authorization", strings.Replace(r.Header.Get("Authorization"), ";host;", ";", 1))
		}},
		{"unsigned date", func(r *http.Request) {
			r.Header.Set("Authorization", strings.Replace(r.Header.Get("Authorization"), ";x-amz-date;", ";", 1))
		}},
		{"unexpected token", func(r *http.Request) { r.Header.Set("X-Amz-Security-Token", "untrusted") }},
		{"duplicate token", func(r *http.Request) { r.Header["X-Amz-Security-Token"] = []string{"one", "two"} }},
		{"unsigned payload", func(r *http.Request) { r.Header.Set("X-Amz-Content-Sha256", "UNSIGNED-PAYLOAD") }},
		{"streaming payload", func(r *http.Request) { r.Header.Set("X-Amz-Content-Sha256", "STREAMING-AWS4-HMAC-SHA256-PAYLOAD") }},
		{"duplicate payload hash", func(r *http.Request) {
			r.Header["X-Amz-Content-Sha256"] = []string{strings.Repeat("a", 64), strings.Repeat("a", 64)}
		}},
		{"malformed query", func(r *http.Request) { r.URL.RawQuery = "a=1&bad=%GG" }},
		{"ambiguous query", func(r *http.Request) { r.URL.RawQuery = "a=1;admin=true" }},
		{"presigned query", func(r *http.Request) { r.URL.RawQuery = "X-Amz-Signature=a&X-Amz-Signature=b" }},
		{"inconsistent raw path", func(r *http.Request) { r.URL.RawPath = "/different%2Fpath" }},
		{"malformed raw path", func(r *http.Request) { r.URL.RawPath = "/bad%GG" }},
		{"opaque URL", func(r *http.Request) { r.URL.Opaque = "//other.test/path" }},
		{"duplicate content length", func(r *http.Request) { r.Header["Content-Length"] = []string{"7", "7"} }},
		{"framing header", func(r *http.Request) { r.Header.Set("X-Repeated", "first\r\nInjected: value") }},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			request := iamSDKRequest(t, http.MethodPost, "/items/one?a=1", []byte("payload"), iamTestTime, "")
			test.change(request)
			tracker := &iamReadTracker{reader: strings.NewReader("payload")}
			request.Body = tracker
			identity, body, status := iamTestVerifier().authenticate(request)
			require.Equal(t, http.StatusForbidden, status)
			require.Zero(t, tracker.reads)
			require.False(t, tracker.closed)
			require.Zero(t, identity)
			require.Nil(t, body)
		})
	}
}

func TestIAMVerifierBindsMethodPathQueryHeadersAndBody(t *testing.T) {
	for _, test := range []struct {
		name   string
		change func(*http.Request)
	}{
		{"method", func(r *http.Request) { r.Method = http.MethodDelete }},
		{"escaped path", func(r *http.Request) { r.URL.Path = "/items/a/b"; r.URL.RawPath = "" }},
		{"query value", func(r *http.Request) { r.URL.RawQuery = "a=2&a=1" }},
		{"removed query", func(r *http.Request) { r.URL.RawQuery = "a=1" }},
		{"added query", func(r *http.Request) { r.URL.RawQuery += "&extra=true" }},
		{"host", func(r *http.Request) { r.Host = "different.example.test:4180" }},
		{"signed header", func(r *http.Request) { r.Header.Set("X-Request-Id", "tampered") }},
		{"body", func(r *http.Request) { r.Body = io.NopCloser(strings.NewReader("changed")) }},
		{"declared hash", func(r *http.Request) { r.Header.Set("X-Amz-Content-Sha256", strings.Repeat("0", 64)) }},
	} {
		t.Run(test.name, func(t *testing.T) {
			request := iamSDKRequest(t, http.MethodPost, "/items/a%2Fb?a=1&a=3", []byte("payload"), iamTestTime, "")
			test.change(request)
			identity, body, status := iamTestVerifier().authenticate(request)
			require.Equal(t, http.StatusForbidden, status)
			require.Zero(t, identity)
			require.Nil(t, body)
		})
	}
	// SigV4 sorts query values. Equivalent order is accepted, while the native
	// original query spelling/order remains available to the integration.
	request := iamSDKRequest(t, http.MethodGet, "/items/one?a=1&a=3", nil, iamTestTime, "")
	request.URL.RawQuery = "a=3&a=1"
	_, _, status := iamTestVerifier().authenticate(request)
	require.Zero(t, status)
	require.Equal(t, "a=3&a=1", request.URL.RawQuery)
}

func TestIAMVerifierSessionTokensRegistryOwnershipAndFreshness(t *testing.T) {
	original := map[string]iamCredential{"local-example-key": {
		secretAccessKey: "local-example-secret", sessionToken: "local-example-token",
		identity: iamIdentity{AccessKey: "untrusted-map-value", AccountID: "111122223333", UserARN: "arn:aws:sts::111122223333:assumed-role/worker/local"},
	}}
	verifier := newIAMVerifier("us-east-1", original)
	verifier.now = func() time.Time { return iamTestTime }
	delete(original, "local-example-key")
	for _, skew := range []time.Duration{-5 * time.Minute, 0, 5 * time.Minute} {
		request := iamSDKRequest(t, http.MethodGet, "/items/one", nil, iamTestTime.Add(skew), "local-example-token")
		identity, _, status := verifier.authenticate(request)
		require.Zero(t, status)
		require.Equal(t, "local-example-key", identity.AccessKey, "lookup key owns accessKey identity")
	}
	for _, change := range []func(*http.Request){
		func(r *http.Request) { r.Header.Del("X-Amz-Security-Token") },
		func(r *http.Request) { r.Header.Set("X-Amz-Security-Token", "wrong-token") },
		func(r *http.Request) {
			r.Header.Set("Authorization", strings.Replace(r.Header.Get("Authorization"), ";x-amz-security-token;", ";", 1))
		},
	} {
		request := iamSDKRequest(t, http.MethodGet, "/items/one", nil, iamTestTime, "local-example-token")
		change(request)
		tracker := &iamReadTracker{reader: strings.NewReader("")}
		request.Body = tracker
		_, _, status := verifier.authenticate(request)
		require.Equal(t, http.StatusForbidden, status)
		require.Zero(t, tracker.reads)
	}
}

type iamFailReader struct{}

func (iamFailReader) Read([]byte) (int, error) { return 0, errors.New("private read error") }

func TestIAMVerifierBoundedReadAndCallerOwnedClosure(t *testing.T) {
	request := iamSDKRequest(t, http.MethodPost, "/items/one", []byte("payload"), iamTestTime, "")
	tracker := &iamReadTracker{reader: strings.NewReader("payload")}
	request.Body = tracker
	_, body, status := iamTestVerifier().authenticate(request)
	require.Zero(t, status)
	require.Equal(t, []byte("payload"), body)
	require.False(t, tracker.closed, "request owner closes the body")
	require.NoError(t, request.Body.Close())
	require.True(t, tracker.closed)

	request = iamSDKRequest(t, http.MethodPost, "/items/one", []byte("payload"), iamTestTime, "")
	request.Body = io.NopCloser(iamFailReader{})
	_, _, status = iamTestVerifier().authenticate(request)
	require.Equal(t, http.StatusBadRequest, status)

	request = iamSDKRequest(t, http.MethodPost, "/items/one", nil, iamTestTime, "")
	request.ContentLength = maxIAMRequestBody + 1
	tracker = &iamReadTracker{reader: strings.NewReader("")}
	request.Body = tracker
	_, _, status = iamTestVerifier().authenticate(request)
	require.Equal(t, http.StatusRequestEntityTooLarge, status)
	require.Zero(t, tracker.reads)

	large := bytes.Repeat([]byte{'x'}, maxIAMRequestBody)
	request = iamSDKRequest(t, http.MethodPost, "/items/one", large, iamTestTime, "")
	_, body, status = iamTestVerifier().authenticate(request)
	require.Zero(t, status)
	require.Len(t, body, maxIAMRequestBody)

	request = iamSDKRequest(t, http.MethodPost, "/items/one", nil, iamTestTime, "")
	request.ContentLength = -1 // Actual HTTP chunked framing can omit a length.
	request.Body = io.NopCloser(io.MultiReader(bytes.NewReader(large), strings.NewReader("x")))
	_, _, status = iamTestVerifier().authenticate(request)
	require.Equal(t, http.StatusRequestEntityTooLarge, status)
}

func TestIAMVerifierNativeCanonicalQueryEncoding(t *testing.T) {
	// AWS canonical ordering sorts encoded names and then encoded values,
	// including prefix keys, empty values, literal plus and encoded slash text.
	query, err := url.ParseQuery("a-=x&a=z&a=a&plus=%2B&space=%20&literal=%252F&empty&%C3%A9=x")
	require.NoError(t, err)
	require.Equal(t, "%C3%A9=x&a=a&a=z&a-=x&empty=&literal=%252F&plus=%2B&space=%20", iamCanonicalQuery(query))
}
